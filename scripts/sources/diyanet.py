"""Fetch Hijri month starts from Diyanet's own daily prayer-time table.

namazvakitleri.diyanet.gov.tr publishes, per city, a yearly table with the
Gregorian date and Diyanet's Hijri date for every day. The Hijri date does not
depend on the city. Every row whose Hijri day is 1 is a month start we can
record. The page only shows today onwards, so records accumulate in
observations/diyanet.json and are never removed.
"""

import html
import re
import sys
import urllib.request
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from common import OBSERVATIONS, load_json, save_json  # noqa: E402

URL = "https://namazvakitleri.diyanet.gov.tr/tr-TR/9541/istanbul-icin-namaz-vakti"
OUT = OBSERVATIONS / "diyanet.json"

GREGORIAN_MONTHS = {
    "Ocak": 1, "Şubat": 2, "Mart": 3, "Nisan": 4, "Mayıs": 5, "Haziran": 6,
    "Temmuz": 7, "Ağustos": 8, "Eylül": 9, "Ekim": 10, "Kasım": 11, "Aralık": 12,
}
HIJRI_MONTHS = {
    "Muharrem": 1, "Safer": 2, "Rebiulevvel": 3, "Rebiülevvel": 3, "Rebiulahir": 4,
    "Rebiülahir": 4, "Cemaziyelevvel": 5, "Cemaziyelahir": 6, "Recep": 7, "Receb": 7,
    "Şaban": 8, "Ramazan": 9, "Şevval": 10, "Zilkade": 11, "Zilkâde": 11, "Zilhicce": 12,
}
ROW = re.compile(
    r"<td>(\d+) (\S+) (\d{4}) \S+</td>\s*<td>(\d+) (\S+) (\d{4})</td>"
)


def fetch_rows():
    request = urllib.request.Request(URL, headers={"User-Agent": "Mozilla/5.0 (ezan-data)"})
    with urllib.request.urlopen(request, timeout=60) as response:
        page = html.unescape(response.read().decode("utf-8"))
    rows = []
    for g_day, g_month, g_year, h_day, h_month, h_year in ROW.findall(page):
        if g_month not in GREGORIAN_MONTHS or h_month not in HIJRI_MONTHS:
            raise RuntimeError(f"Unknown month name in Diyanet table: {g_month!r} / {h_month!r}")
        rows.append((
            date(int(g_year), GREGORIAN_MONTHS[g_month], int(g_day)),
            int(h_year), HIJRI_MONTHS[h_month], int(h_day),
        ))
    if len(rows) < 25:
        raise RuntimeError(f"Diyanet table looks broken: only {len(rows)} rows parsed")
    return sorted(set(rows))


def check_continuity(rows):
    """Consecutive days must advance the Hijri date by exactly one day."""
    for (d1, y1, m1, h1), (d2, y2, m2, h2) in zip(rows, rows[1:]):
        if (d2 - d1).days != 1:
            continue  # gaps in the published table are fine
        same_month = (y1, m1) == (y2, m2) and h2 == h1 + 1
        new_month = h2 == 1 and h1 in (29, 30)
        if not (same_month or new_month):
            raise RuntimeError(f"Diyanet table jumps from {h1}/{m1}/{y1} to {h2}/{m2}/{y2} on {d2}")


def main():
    rows = fetch_rows()
    check_continuity(rows)
    data = load_json(OUT) if OUT.exists() else {"records": []}
    existing = {(r["hijri_year"], r["hijri_month"]): r for r in data["records"]}
    today = date.today().isoformat()
    changes = []
    for g_date, h_year, h_month, h_day in rows:
        if h_day != 1:
            continue
        record = {
            "target": "diyanet",
            "hijri_year": h_year,
            "hijri_month": h_month,
            "first_day": g_date.isoformat(),
            "source": "Diyanet daily Hijri table",
            "url": URL,
            "recorded_at": today,
        }
        old = existing.get((h_year, h_month))
        if old is None:
            changes.append(f"NEW {h_year}/{h_month} starts {record['first_day']}")
        elif old["first_day"] != record["first_day"]:
            changes.append(
                f"CHANGED {h_year}/{h_month}: Diyanet now says {record['first_day']} (was {old['first_day']})"
            )
        else:
            continue
        existing[(h_year, h_month)] = record
    data["_comment"] = (
        "Generated by scripts/sources/diyanet.py. Month starts read from Diyanet's daily "
        "Hijri table; kept forever because the page only shows today onwards."
    )
    data["records"] = [existing[k] for k in sorted(existing)]
    save_json(OUT, data)
    print(f"Diyanet: {len(rows)} days parsed")
    for line in changes:
        print(line)


if __name__ == "__main__":
    main()
